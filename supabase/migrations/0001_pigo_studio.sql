create table if not exists public.gallery_projects(
 id uuid primary key default gen_random_uuid(), title text not null, category text not null, description text,
 cover_url text, published boolean not null default false, created_at timestamptz not null default now()
);
create table if not exists public.leads(
 id uuid primary key default gen_random_uuid(), code text unique not null, name text not null, phone text not null, email text,
 city text not null, sector text, preferred_contact text, project_type text, project_label text, quote_mode text,
 supply_mode text, needs_visit boolean not null default false, risk_level text, assessment jsonb, estimate jsonb, project_items jsonb not null default '[]'::jsonb, conversation jsonb,
 status text not null default 'new' check(status in ('new','reviewing','visit_scheduled','quoted','won','lost')), created_at timestamptz not null default now()
);
create table if not exists public.lead_images(
 id uuid primary key default gen_random_uuid(), lead_id uuid not null references public.leads(id) on delete cascade, storage_path text not null, created_at timestamptz not null default now()
);
create table if not exists public.ai_rate_limits(
 id bigint generated by default as identity primary key, client_hash text not null, created_at timestamptz not null default now()
);
create index if not exists ai_rate_limits_client_time_idx on public.ai_rate_limits(client_hash, created_at desc);
create table if not exists public.ai_usage_log(
 id bigint generated by default as identity primary key, model text, input_tokens int not null default 0, output_tokens int not null default 0,
 scope text, accepted boolean not null default true, created_at timestamptz not null default now()
);
create or replace function public.ai_tokens_today() returns bigint language sql stable security definer set search_path=public as $$
 select coalesce(sum(input_tokens + output_tokens),0)::bigint from public.ai_usage_log where created_at >= date_trunc('day', now())
$$;
create table if not exists public.notification_outbox(
 id bigint generated by default as identity primary key, lead_code text, channel text, status text, payload jsonb, created_at timestamptz not null default now()
);

