create extension if not exists pgcrypto;
create table if not exists public.profiles(
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text,
 role text not null default 'staff' check(role in ('admin','staff')),
 created_at timestamptz not null default now()
);
create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$ begin insert into public.profiles(id,full_name) values(new.id,coalesce(new.raw_user_meta_data->>'full_name','')); return new; end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path=public as $$ select exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin') $$;

create table if not exists public.catalog_items(
 id uuid primary key default gen_random_uuid(), brand text not null, reference text not null, name text not null,
 category text not null default 'General', unit text not null default 'barra', bar_length_m numeric,
 weight_kg_m numeric, dimensions_text text, cost_price numeric not null default 0, sale_price numeric not null default 0,
 active boolean not null default true, source_name text, source_page int, notes text, created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 unique(brand,reference)
);
create table if not exists public.service_rates(
 id uuid primary key default gen_random_uuid(), service_key text unique not null, label text not null,
 unit text not null default 'm2' check(unit in ('m2','ml','unit')), material_rate numeric not null default 0,
 accessory_rate numeric not null default 0, labor_rate numeric not null default 0, installation_rate numeric not null default 0,
 minimum_charge numeric not null default 0, waste_percent numeric not null default 10, margin_percent numeric not null default 20,
 error_percent numeric not null default 15, auto_quote boolean not null default false, updated_at timestamptz not null default now()
);
